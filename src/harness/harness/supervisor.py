"""Harness supervisor: load config, seed the data tree, serve the gateway.

Entry point of the harness container runtime (design point P1: one single
container runs the whole harness 24/7, booted by a process supervisor, with
this module as the supervised program). It resolves the harness configuration
via :func:`harness.config.load_config`, idempotently seeds the on-disk
directory tree under ``storage.data_dir`` via :func:`ensure_data_tree`, and
then either prints a ``--check`` report (config + tree) or serves the R6
gateway FastAPI app via :func:`harness.gateway.app.create_app` under uvicorn
(:func:`build_app` keeps the zero-arg R1 stub for test compat). Configuration
problems surface on stderr as ``config error: ...`` with exit code 2; a
graceful SIGTERM/SIGINT (handled by uvicorn) makes the server return with
exit code 0.
"""

#   Deploy-time (container): supervisord program runs
#       PYTHONPATH=/app/harness python -m harness.supervisor
#   (PYTHONPATH=/app/harness is the deploy-time package home at /app/harness; tests run from
#   src/harness via pyproject pythonpath=["."] instead - do not confuse the two.)

from __future__ import annotations

import argparse
import asyncio
import logging
import os
import pathlib
import sys
from typing import Any

import harness.persist
from harness.bus import Bus
from harness.config import HarnessConfig, load_config
from harness.errors import ConfigError, ConfigLoadError
from harness.session_manager import SessionManager
from harness.skills import SkillsEngine

__all__ = ["build_app", "ensure_data_tree", "load_config", "main"]

_DATA_TREE_DIRS: tuple[str, ...] = ("memory", "skills", "sessions", "tasks/inbox", "state", "logs")
_SKILL_INDEX_CONTENT = "# Skill index (generated by harness/skills.py at R3)\n"


def build_app(
    cfg: HarnessConfig | None = None,
    bus: Bus | None = None,
    manager: SessionManager | None = None,
) -> Any:
    """Build the gateway FastAPI app (zero-arg form kept for R1 compat).

    With ALL arguments None this returns the R1 stub app (``GET /healthz`` ->
    ``{"ok": true}``) unchanged and must NOT call ``load_config()`` (real
    config loads are forbidden in tests). With the real ``(cfg, bus, manager)``
    triple it returns the R6 gateway via
    :func:`harness.gateway.app.create_app` (lazy import above so ``--check``
    and module import never pull in the gateway)."""
    if cfg is None and bus is None and manager is None:
        from fastapi import FastAPI

        app = FastAPI(title="harness-gateway")

        @app.get("/healthz")
        async def healthz() -> dict[str, bool]:
            return {"ok": True}

        return app
    from harness.gateway.app import create_app

    return create_app(cfg, bus, manager)


def ensure_data_tree(cfg: HarnessConfig) -> list[str]:
    """Idempotently seed the data tree under ``cfg.storage.data_dir``.

    Creates the required directories, then writes seed files only when still
    missing: ``skills/INDEX.md``, the empty ``logs/harness.log``, and
    ``state/budgets.json`` (atomically via :class:`harness.persist.
    AtomicCounter`). Prints nothing and returns no paths.
    """
    for rel in _DATA_TREE_DIRS:
        os.makedirs(os.path.join(cfg.storage.data_dir, rel), exist_ok=True)

    index_md = pathlib.Path(cfg.storage.data_dir, "skills", "INDEX.md")
    if not index_md.exists():
        harness.persist.append_text(index_md, _SKILL_INDEX_CONTENT)

    log_file = pathlib.Path(cfg.storage.data_dir, "logs", "harness.log")
    if not log_file.exists():
        harness.persist.append_text(log_file, "")

    budgets = pathlib.Path(cfg.storage.data_dir, "state", "budgets.json")
    if not budgets.exists():
        harness.persist.AtomicCounter(budgets).save()

    return []


def _print_tree(cfg: HarnessConfig) -> None:
    """Print a sorted ``check: <path> ok`` line per dir/file under data_dir."""
    for root, _dirs, files in sorted(os.walk(cfg.storage.data_dir)):
        rel = os.path.relpath(root, cfg.storage.data_dir)
        print(f"check: {rel or (chr(46))} ok")
        for name in sorted(files):
            file_rel = os.path.relpath(os.path.join(root, name), cfg.storage.data_dir)
            print(f"check: {file_rel} ok")


def _boot_skills_index(cfg: HarnessConfig) -> None:
    """Best-effort boot-time skills INDEX.md rebuild; never raises (boot
    must not crash): an index failure degrades to a warning log only."""
    try:
        index_text = SkillsEngine(cfg).build_index()
        logging.getLogger("harness.supervisor").info(
            "skills index rebuilt: %d chars", len(index_text)
        )
    except (OSError, ValueError) as exc:
        logging.getLogger("harness.supervisor").warning("skills index rebuild failed: %s", exc)


async def _start_bot(cfg: HarnessConfig, bus: Bus, manager: SessionManager) -> Any:
    """Start the Discord bot on the running loop when enabled + tokened (ARCH 2.8).

    Disabled (None + log) when cfg.discord.enabled is False or DISCORD_BOT_TOKEN is
    unset/empty — the harness stays fully web-usable without it. The heavy discord
    import happens only in the enabled path (lazy, inside spawn_bot)."""
    if not cfg.discord.enabled:
        logging.getLogger("harness.supervisor").info("discord bot disabled: discord.enabled false")
        return None
    if not (os.environ.get("DISCORD_BOT_TOKEN") or "").strip():
        logging.getLogger("harness.supervisor").info("discord bot disabled: DISCORD_BOT_TOKEN unset")
        return None
    from harness.gateway.discord_bot import spawn_bot

    return await spawn_bot(cfg, bus, manager)


async def _serve(cfg: HarnessConfig) -> int:
    """Serve the gateway app until uvicorn's own signal handling stops it.

Boot order per ARCHITECTURE.md section 3.4: replay session state from
disk and task state (before the gateway serves), log the ready line,
build the real R6 gateway via the lazy-imported
:func:`harness.gateway.app.create_app` (imported
inside this function so ``--check`` and module import stay gateway-free),
close the bus on shutdown. The task loop (WP3): :class:`harness.taskloop.
TaskLoop` is constructed after the session replay, boots with its sync
replay (counts logged on an INFO line), starts its watcher/runner before
the gateway serves, and is stopped in the shutdown ``finally`` (bot stop,
taskloop stop, bus close order). M-5b (``server.behind_proxy``): the TLS/reverse
proxy termination is external (section 5.1); when ``cfg.server.behind_proxy``
is set, uvicorn additionally trusts ``X-Forwarded-For`` from localhost
(``proxy_headers=True``, ``forwarded_allow_ips="127.0.0.1"``) so client-keyed
rate limits see the real client; left untouched when False."""
    bus = Bus()
    manager = SessionManager(cfg, bus=bus)
    counts = manager.replay()
    logging.getLogger("harness.supervisor").info(SessionManager.ready_line(counts))
    _boot_skills_index(cfg)
    from harness.taskloop import TaskLoop

    taskloop = TaskLoop(cfg, manager, bus=bus)
    replay_counts = taskloop.replay()
    logging.getLogger("harness.supervisor").info(
        "tasks replayed: requeued=%d failed_restarted=%d gate_restored=%d deps_waiting=%d",
        replay_counts.get("requeued", 0),
        replay_counts.get("failed_restarted", 0),
        replay_counts.get("gate_restored", 0),
        replay_counts.get("deps_waiting", 0),
    )
    taskloop.start()
    bot: Any | None = None
    bot = await _start_bot(cfg, bus, manager)
    from harness.gateway.app import create_app

    # R10/D18: the task loop instance is wired so the POST /api/tasks/answer
    # gate route reaches TaskLoop.answer (the same resume path as Discord).
    app = create_app(cfg, bus, manager, taskloop_=taskloop)
    import uvicorn

    if cfg.server.behind_proxy:
        # M-5b: TLS/reverse-proxy termination is external (section 5.1); this
        # only makes uvicorn trust X-Forwarded-For from localhost when set.
        config = uvicorn.Config(
            app,
            host=cfg.server.host,
            port=cfg.server.port,
            log_level="info",
            proxy_headers=True,
            forwarded_allow_ips="127.0.0.1",
        )
    else:
        config = uvicorn.Config(
            app, host=cfg.server.host, port=cfg.server.port, log_level="info"
        )
    server = uvicorn.Server(config)
    try:
        await server.serve()
    finally:
        if bot is not None:
            try:
                await bot.stop()
            except Exception:  # noqa: BLE001 — shutdown must not mask the real exit
                logging.getLogger("harness.supervisor").warning("discord bot stop failed")
        await taskloop.stop()
        await bus.aclose()
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: ``--check`` validates config and prints the data tree."""
    parser = argparse.ArgumentParser(
        prog="harness.supervisor", description="harness supervisor and gateway entry point"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the config, seed the data tree, print it, and exit",
    )
    parser.add_argument("--config", default=None, help="path to the YAML config file")
    args = parser.parse_args(argv)
    try:
        cfg = load_config(args.config)
    except (ConfigError, ConfigLoadError) as exc:
        print(f"config error: {exc}", file=sys.stderr)
        return 2
    ensure_data_tree(cfg)
    if args.check:
        print("config ok")
        _print_tree(cfg)
        return 0
    return asyncio.run(_serve(cfg))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
